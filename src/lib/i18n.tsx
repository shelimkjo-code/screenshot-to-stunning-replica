const dict: Record<Lang, Record<TKey, string>> = { en, bn };

const BN_DIGITS = ["০", "১", "২", "৩", "৪", "৫", "৬", "৭", "৮", "৯"];

interface I18nCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: TKey) => string;
  n: (v: number | string) => string;
}
const Ctx = createContext<I18nCtx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("bn");
  useEffect(() => {
    const saved = window.localStorage.getItem("lang");
    if (saved === "en" || saved === "bn") setLangState(saved);
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    window.localStorage.setItem("lang", l);
  }, []);
  const t = useCallback((k: TKey) => dict[lang][k], [lang]);
  const n = useCallback(
    (v: number | string) => (lang === "bn" ? String(v).replace(/\d/g, (d) => BN_DIGITS[Number(d)]!) : String(v)),
    [lang],
  );
  return <Ctx.Provider value={{ lang, setLang, t, n }}>{children}</Ctx.Provider>;
}

export function useI18n() {
  const c = useContext(Ctx);
  if (!c) throw new Error("useI18n must be used inside I18nProvider");
  return c;
}
